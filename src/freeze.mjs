// Freeze one request: exact committed source, hashes, evaluator status and the job wrapper.
import fs from 'node:fs';
import path from 'node:path';
import {git, gitStatus} from './git.mjs';
import {FORBIDDEN} from './request.mjs';
import {readJson, writeAtomic, writeJson, sha256, shellQuote, isoNow} from './fsutil.mjs';

export const ARC_VERSION = (() => {
  try { return git(path.dirname(new URL(import.meta.url).pathname), ['describe', '--always', '--dirty'], {timeout: 10000}).trim(); }
  catch { return 'unknown'; }
})();

// git diff exit 0 = identical, 1 = differs. Anything else is a transient error.
export function evaluatorStatus(repo, evaluator, commit) {
  if (!evaluator) return null;
  const paths = evaluator.paths.map(p => p.replace(/\/+$/, ''));
  const r = gitStatus(repo, ['diff', '--quiet', evaluator.commit, commit, '--', ...paths]);
  if (!r.ok && r.code !== 1) throw Error(`evaluator check failed: ${r.stderr.trim()}`);
  const trees = {};
  for (const p of paths) {
    const t = gitStatus(repo, ['rev-parse', `${evaluator.commit}:${p}`]);
    trees[p] = t.ok ? t.stdout.trim() : null;
  }
  return {commit: evaluator.commit, status: r.ok ? 'unmodified' : 'modified', trees};
}

const dq = s => `"${String(s).replace(/(["\\`])/g, '\\$1')}"`; // double-quoted: $VARS expand at run time

export function runScript({campaign, request, out, forbidden}) {
  const {config} = campaign;
  const env = Object.entries(config.job_env ?? {}).map(([k, v]) => `export ${k}=${dq(v)}`);
  const blocked = [...new Set([...FORBIDDEN, ...forbidden])].map(shellQuote).join(' ');
  const outputs = request.expected_outputs.map(p => `arc_output ${shellQuote(p)} ${shellQuote(JSON.stringify(p))}`).join("; printf ','; ");
  return `#!/bin/bash
# Generated by arc. Runs ${request.id} from the frozen source of ${request.source_commit}.
set -euo pipefail
export ARC_CAMPAIGN=${shellQuote(config.id)} ARC_REQUEST_ID=${shellQuote(request.id)} ARC_SEED=${shellQuote(request.seed)}
export ARC_RUN_DIR=${shellQuote(out)}
export ARC_SOURCE="$ARC_RUN_DIR/source"
export OMP_NUM_THREADS="\${SLURM_CPUS_PER_TASK:-1}" MKL_NUM_THREADS="\${SLURM_CPUS_PER_TASK:-1}" OPENBLAS_NUM_THREADS="\${SLURM_CPUS_PER_TASK:-1}"
${env.join('\n')}
started="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
arc_output() {
  local f="$ARC_RUN_DIR/$1"
  if [ -f "$f" ]; then printf '{"path":%s,"sha256":"%s","bytes":%s}' "$2" "$(sha256sum "$f" | cut -d' ' -f1)" "$(stat -c %s "$f")"
  elif [ -d "$f" ]; then printf '{"path":%s,"directory":true}' "$2"
  else printf '{"path":%s,"missing":true}' "$2"; fi
}
arc_finish() {
  local status=$?
  local base
  base="$(printf '"exit_code":%d,"job_id":"%s","started_at":"%s","finished_at":"%s"' "$status" "\${SLURM_JOB_ID:-}" "$started" "$(date -u +%Y-%m-%dT%H:%M:%SZ)")"
  printf '{%s}\\n' "$base" > "$ARC_RUN_DIR/execution.json"
  # Result receipt: a fingerprint of each expected output as the job left it. Written second, so a kill
  # during hashing still leaves the basic record.
  { printf '{%s,"outputs":[' "$base"; ${outputs}; printf ']}\\n'; } > "$ARC_RUN_DIR/.execution.json.tmp" &&
    mv "$ARC_RUN_DIR/.execution.json.tmp" "$ARC_RUN_DIR/execution.json"
}
trap arc_finish EXIT
# Only the controller submits or cancels jobs: shadow scheduler commands inside the job.
shims="$ARC_RUN_DIR/.arc-shims"
mkdir -p "$shims"
for c in ${blocked}; do
  printf '#!/bin/sh\\necho "arc: $(basename "$0") is blocked inside campaign jobs; only the controller submits" >&2\\nexit 97\\n' > "$shims/$c"
  chmod +x "$shims/$c"
done
export PATH="$shims:$PATH"
if [ ! -d "$ARC_SOURCE" ]; then
  tmp="$ARC_RUN_DIR/.source-$$"
  mkdir -p "$tmp"
  tar -xf "$ARC_RUN_DIR/source.tar" -C "$tmp"
  mv "$tmp" "$ARC_SOURCE"
fi
cd "$ARC_SOURCE"
bash ${shellQuote(request.script)}
`;
}

// Idempotent: a finished freeze (provenance.json for the same request hash) is reused.
export function freeze({campaign, record, route, forbidden = []}) {
  const {config, paths} = campaign;
  const request = record.request;
  const out = path.join(paths.artifacts, request.id);
  const provFile = path.join(out, 'provenance.json');
  const prior = readJson(provFile);
  if (prior && prior.request_sha256 === record.sha256) return {out, provenance: prior};

  fs.mkdirSync(out, {recursive: true, mode: 0o700});
  const tar = path.join(out, 'source.tar');
  git(config.repo, ['archive', '--format=tar', `--output=${tar}.tmp`, request.source_commit]);
  fs.renameSync(`${tar}.tmp`, tar);
  const script = git(config.repo, ['show', `${request.source_commit}:${request.script}`]);
  let ignored = '';
  if (fs.existsSync(paths.worktree)) ignored = gitStatus(paths.worktree, ['status', '--porcelain', '--untracked-files=all']).stdout;

  writeJson(path.join(out, 'request.json'), request);
  writeAtomic(path.join(out, 'run.sh'), runScript({campaign, request, out, forbidden}), 0o700);
  const provenance = {
    campaign: config.id, request_id: request.id, request_sha256: record.sha256, request,
    source_commit: request.source_commit,
    archive_sha256: sha256(fs.readFileSync(tar)),
    script_sha256: sha256(script),
    evaluator: evaluatorStatus(config.repo, config.evaluator, request.source_commit),
    ignored_worktree_changes: ignored.split('\n').filter(Boolean),
    route: {args: route.args, note: route.note ?? null},
    arc_version: ARC_VERSION,
    created_at: isoNow(),
  };
  writeJson(provFile, provenance);
  return {out, provenance};
}

export function studyRecord({campaign, record, provenance, out}) {
  const r = record.request;
  return {
    id: `${campaign.config.id}-${r.id}`,
    title: `${campaign.config.id}: ${r.id}`,
    campaign: campaign.config.id,
    hypothesis: r.hypothesis, baseline: r.baseline, evaluation: r.evaluation,
    seed: r.seed, data_provenance: r.data_provenance, config_description: r.config_description,
    source_commit: r.source_commit,
    submitted_after: (record.submitted_at ?? isoNow()).slice(0, 10),
    jobs: [{id: record.job_id, purpose: `${r.kind}: ${r.hypothesis}`}],
    evidence_paths: [
      path.join(out, 'request.json'), path.join(out, 'provenance.json'), path.join(out, 'execution.json'),
      path.join(out, `slurm-${record.job_id}.log`), ...r.expected_outputs.map(p => path.join(out, p)),
    ],
    evaluator_status: provenance?.evaluator?.status ?? null,
  };
}
